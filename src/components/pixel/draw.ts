export function text(ctx: CanvasRenderingContext2D, value: string, x: number, y: number, scale = 1) {
  ctx.fillStyle = '#000'
  for (const char of value.toUpperCase()) {
    const glyph = glyphs[char]
    if (glyph) {
      glyph.split('/').forEach((row, gy) => [...row].forEach((bit, gx) => {
        if (bit === '1') ctx.fillRect(x + gx * scale, y + gy * scale, scale, scale)
      }))
      x += 6 * scale
    } else if (char === ' ') x += 4 * scale
    else {
      // Chinese is rasterized to the same logical pixel buffer as other elements.
      ctx.font = `${16 * scale}px "PingFang SC", "Microsoft YaHei", sans-serif`
      ctx.textBaseline = 'top'
      ctx.fillText(char, x, y - scale, 16 * scale)
      x += 17 * scale
    }
  }
}
export function frame(ctx: CanvasRenderingContext2D, x: number, y: number, w: number, h: number) {
  ctx.fillStyle = '#000'
  ctx.fillRect(x, y, w, 1); ctx.fillRect(x, y + h - 1, w, 1)
  ctx.fillRect(x, y, 1, h); ctx.fillRect(x + w - 1, y, 1, h)
}
